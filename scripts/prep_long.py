def doc_id(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:12]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    id_by_title, corpus = {}, []
    for title, body in DOCS:
        d = doc_id(body)
        id_by_title[title] = d
        corpus.append({"id": d, "title": title, "body": body})

    items = []
    for i, (q, ans, titles) in enumerate(ITEMS, 1):
        items.append({
            "id": f"long-{i:02d}",
            "question": q,
            "answer": ans or "",
            "gold_ids": [id_by_title[t] for t in (titles or [])],
        })

    with open(os.path.join(args.out, "corpus.jsonl"), "w", encoding="utf-8") as f:
        for d in corpus:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(os.path.join(args.out, "items.jsonl"), "w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")

    lens = [len(b) for _, b in DOCS]
    manifest = {
        "source": "自造：中文法律类长文档（分条结构，答案多在中段）",
        "synthetic": True,
        "license": "自造（探针用）",
        "docs": len(DOCS),
        "items": len(items),
        "doc_chars": {"min": min(lens), "max": max(lens), "avg": sum(lens) // len(lens)},
        "doc_id_scheme": "正文 sha256 前 12 位",
        "note": "**不是真实语料**：目的是把长文档这个形态**测出来**（现有读数全部来自"
                "短条文）。三类题：答案埋中段、跨两篇、口语鸿沟；另有干扰长文抢窗口；"
                "末尾 4 题语料外（应拒答）。",
        "metrics": {
            "evidence_hit": "金标文档是否出现在检索窗口里",
            "window_hit": "引用窗口的文本里是否**真的包含答案片段**（长文档最脆弱的一环）",
            "refusal": "语料外的问题是否拒答",
        },
    }
    with open(os.path.join(args.out, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    print(f"长文档语料：{len(DOCS)} 篇（{min(lens)}–{max(lens)} 字，均值 {sum(lens)//len(lens)}）/ {len(items)} 题 → {args.out}")
    print(f"  可答 {sum(1 for _,a,_ in ITEMS if a)} 题，语料外 {sum(1 for _,a,_ in ITEMS if not a)} 题")
    return 0


