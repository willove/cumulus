def doc_id(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:12]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="输出目录（corpus.jsonl / items.jsonl / manifest.json）")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    docs, items = [], []
    for title, body in DISTRACTOR_SEEDS:
        docs.append({"id": doc_id(body), "title": title, "body": body})
    for i, (title, body, qas) in enumerate(PAIRS, 1):
        did = doc_id(body)
        docs.append({"id": did, "title": title, "body": body})
        for j, (q, a) in enumerate(qas, 1):
            items.append({
                "id": f"gap-{i}-{j}",
                "question": q,
                "answer": a,
                "gold_ids": [did],
                # 这一维不标：鸿沟语料量的是检索面（evidence / bridge），不是"该不该检索"
            })

    with open(os.path.join(args.out, "corpus.jsonl"), "w", encoding="utf-8") as f:
        for d in docs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(os.path.join(args.out, "items.jsonl"), "w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")

    manifest = {
        "source": "合成：同一件事的书面文档 × 口语问句（词汇鸿沟探针）",
        "synthetic": True,
        "license": "自造（探针用）",
        "docs": len(docs),
        "gold_docs": len(PAIRS),
        "distractors": len(DISTRACTOR_SEEDS),
        "why_distractors": "干扰文档用问句的表面词却不含答案：首程够不着金标 → 路由升级 → 桥才上场。",
        "items": len(items),
        "doc_id_scheme": "正文 sha256 前 12 位",
        "note": "**不是真实语料**：只为让 LLM 词汇桥被触发并可量。读数只在这份语料上"
                "有意义，不代表任何真实知识库上的表现。问句刻意不与文档共享内容词，"
                "所以关桥会掉 evidence、开桥会升——这正是要量的差。",
        "arms": {
            "关桥": "CUMULUS_BRIDGE=0",
            "开桥无护栏": "CUMULUS_BRIDGE_GUARD=0",
            "开桥带护栏": "（默认）",
        },
    }
    with open(os.path.join(args.out, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    print(f"语料 {len(docs)} 篇 / 问句 {len(items)} 条 → {args.out}")
    print("三臂对照：")
    for k, v in manifest["arms"].items():
        print(f"  {k:12s} {v}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())