"""prep_gap.py — 造一份**词汇鸿沟**语料，专门让 LLM 词汇桥被触发并可量。

为什么需要它：桥（question → 检索词翻译）的收益/代价**在现有语料上量不出来**——
DuReader hard 40 题里桥一次没走（问句与文档都用词），所以"桥有没有用、护栏有没有
用"至今只有行为测试兜着，没有数据。这份语料用**同一件事的两种说法**构造鸿沟：

    文档（书面/正式）：犬类饲养管理规程 / 差旅费管理办法 / …
    问句（口语）：     养狗扰民谁管 / 出差住宿能报多少 / …

于是：
- 关桥（朴素路）会因为词面不共享而**检索不到**（evidence 掉）；
- 开桥且桥扩得准 → 检索得到（evidence 升）；
- 开桥但桥扩偏 → 护栏应当把它**弃用**（回到朴素结果）。

**它不是真实语料**，是为了让这条链能被测量的**探针**：读数只在这份语料上有意义，
不代表任何真实知识库上的表现。（诚实标注，别拿它当基准。）

**第一版探针失败过（值得记下来）**：只有 5 篇文档、topk=9 → 检索几乎总把全部文档召回，
evidence 恒 90%（平凡的：金标必然在召回里），于是首程"够用"、**桥一次没走**——
三臂读数完全相同，什么也没量到。修法两条：语料要**远大于 topk**（否则召回平凡）、
干扰文档要**用问句的表面词**（狗/扰民/扔垃圾）却不含答案（这样首程够不着金标、
才会升级，才会走桥）。

用法：
    python3 scripts/prep_gap.py --out ~/datasets/gap
"""
